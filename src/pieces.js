export function getKickTests(type, from, to) {
  if (type === "O") return [[0, 0]];
  return (type === "I" ? I_KICKS : JLSTZ_KICKS)[`${from}>${to}`] || [[0, 0]];
}

export function cellsFor(piece) {
  return PIECES[piece.type][piece.rotation].map(([x, y]) => [piece.x + x, piece.y + y]);
}
